"""Generate the Markdown repository map from the folder contracts."""

import argparse
import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
MAP = ROOT / "map" / "README.md"


def read_contract(folder):
    path = folder / "CONTEXT.md"
    relative = path.relative_to(ROOT).as_posix()
    if not path.is_file():
        raise ValueError(f"Missing folder contract: {relative}")

    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0] != "---" or "---" not in lines[1:]:
        raise ValueError(f"{relative}: missing frontmatter")
    frontmatter = lines[1:lines.index("---", 1)]

    step = None
    if folder.parent.name == "modules":
        steps = [line for line in frontmatter if line.startswith("build_step:")]
        if len(steps) != 1 or not re.fullmatch(r"build_step: [1-4]", steps[0]):
            raise ValueError(f"{relative}: expected one build_step from 1 to 4")
        step = int(steps[0][-1])

    fields = {}
    for key in ("consumes", "produces"):
        entries = [line[len(key) + 1:] for line in frontmatter if line.startswith(f"{key}:")]
        if len(entries) != 1:
            raise ValueError(f"{relative}: expected one {key} array")
        try:
            values = json.loads(entries[0])
        except json.JSONDecodeError as error:
            raise ValueError(f"{relative}: invalid {key} array: {error.msg}") from error
        if not isinstance(values, list) or any(
            not isinstance(value, str) or not value.strip() for value in values
        ):
            raise ValueError(f"{relative}: {key} must be an array of nonempty strings")
        fields[key] = values
    return path, step, fields["consumes"], fields["produces"]


def render():
    modules = ROOT / "modules"
    if not modules.is_dir():
        raise ValueError("Missing modules directory")
    folders = [ROOT / "contracts", *sorted(path for path in modules.iterdir() if path.is_dir())]
    contracts = [read_contract(folder) for folder in folders]
    nodes = {path.resolve(): f"folder{index}" for index, (path, _, _, _) in enumerate(contracts)}
    lines = [
        "# Repository map",
        "",
        "<!-- Generated by python -I _tools/map.py -->",
        "",
        "Arrows point to contracts a top-level folder may read. Lane-specific inputs are listed inside the parent contract.",
        "",
        "See the [target map](target.md) for how the finished application will work.",
        "",
        "```mermaid",
        "flowchart TD",
    ]
    edges = []
    table = ["| Folder contract | Build step | Outputs |", "| --- | --- | --- |"]
    for path, step, consumes, produces in contracts:
        folder = path.parent.relative_to(ROOT).as_posix()
        if not re.fullmatch(r"(?:modules/)?[a-z][a-z0-9-]*", folder):
            raise ValueError(f"Invalid folder name: {folder}")
        node = nodes[path.resolve()]
        lines.append(f'    {node}["{folder}"]')
        for dependency in consumes:
            target = (path.parent / dependency).resolve()
            if Path(dependency).is_absolute() or target not in nodes:
                raise ValueError(f"{folder}/CONTEXT.md: unknown contract {dependency}")
            edges.append(f"    {node} --> {nodes[target]}")
        outputs = ", ".join(produces).replace("|", r"\|") or "None"
        build_step = {None: "—", 1: "1 (decided)"}.get(step, f"{step} (proposed)")
        table.append(f"| [{folder}](../{folder}/CONTEXT.md) | {build_step} | {outputs} |")
    return "\n".join([*lines, *edges, "```", "", *table, ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the committed map needs updating.")
    args = parser.parse_args()
    try:
        generated = render()
        if args.check:
            if not MAP.is_file() or MAP.read_text(encoding="utf-8") != generated:
                raise ValueError("map/README.md needs updating. Run python -I _tools/map.py.")
            print("Folder contracts and generated map are current.")
        else:
            MAP.parent.mkdir(exist_ok=True)
            MAP.write_text(generated, encoding="utf-8", newline="\n")
    except (OSError, ValueError) as error:
        parser.exit(1, f"{error}\n")


if __name__ == "__main__":
    main()
